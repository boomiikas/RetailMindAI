"""Recommendations API endpoints for RetailMind AI."""
from typing import List, Dict, Any, Optional
from fastapi import APIRouter, Depends, Query, HTTPException
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from backend.app.database.session import get_db
from backend.app.models import DecisionRecord, Product, Store, RiskEvent
from backend.app.schemas.contracts import RecommendationItem, GenerateRecommendationRequest
from backend.app.services.optimization.optimizer import RetailOptimizer
from backend.app.services.llm.groq_service import groq_llm

router = APIRouter(prefix="/recommendations", tags=["Recommendations"])

@router.get("")
async def list_recommendations(
    status: Optional[str] = Query(None, description="Decision status filter (PENDING, APPROVED, REJECTED, or None for all)"),
    db: AsyncSession = Depends(get_db)
):
    """Retrieves all active proposed recommendations generated by the optimization engine."""
    stmt = select(DecisionRecord)
    if status and status.upper() != "ALL":
        stmt = stmt.where(DecisionRecord.decision_status == status.upper())
    rows = (await db.execute(stmt)).scalars().all()

    results = []
    for d in rows:
        results.append({
            "decision_id": d.decision_id,
            "version": d.current_version,
            "status": d.decision_status,
            "execution_status": d.execution_status,
            "recommendation": d.original_recommendation_snapshot,
            "created_at": d.created_at.isoformat()
        })
    return results

@router.get("/{decision_id}")
async def get_decision_recommendations(
    decision_id: str,
    db: AsyncSession = Depends(get_db)
):
    """Retrieves decision record and its version history."""
    dec = await db.get(DecisionRecord, decision_id)
    if not dec:
        raise HTTPException(status_code=404, detail=f"Decision {decision_id} not found")
    return {
        "decision_id": dec.decision_id,
        "current_version": dec.current_version,
        "decision_status": dec.decision_status,
        "execution_status": dec.execution_status,
        "recommendation": dec.original_recommendation_snapshot,
        "created_at": dec.created_at.isoformat(),
        "updated_at": dec.updated_at.isoformat()
    }

@router.post("/generate")
async def generate_recommendations(
    payload: GenerateRecommendationRequest,
    db: AsyncSession = Depends(get_db)
):
    """Triggers Pyomo MILP optimization to generate and rank feasible business interventions."""
    optimizer = RetailOptimizer(db)
    recs = await optimizer.optimize_inventory_decisions(
        dest_store_id=payload.store_id,
        product_id=payload.product_id
    )
    if not recs:
        raise HTTPException(status_code=400, detail="Unable to compute feasible recommendations")

    # Generate Groq LLM explanation for the top recommendation
    top = recs[0]
    llm_explanation = await groq_llm.explain_recommendation(
        problem_detected=f"Shortfall at {payload.store_id}",
        affected_store=payload.store_id,
        affected_product=payload.product_id,
        recommended_action=top["action_type"],
        quantity=top.get("quantity", 0),
        expected_profit=top.get("expected_net_profit", 0.0),
        alternatives=recs[1:],
        shap_drivers=top.get("shap_summary", []) or []
    )

    return {
        "store_id": payload.store_id,
        "product_id": payload.product_id,
        "total_alternatives": len(recs),
        "primary_recommendation": top,
        "alternatives": recs[1:],
        "groq_business_explanation": llm_explanation
    }
